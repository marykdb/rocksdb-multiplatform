    @Test
    fun presetsProduceDatabasesThatCanWriteAndRead() {
        val presets: List<(Options) -> Unit> = listOf(
            { it.optimizeForPointLookup(8) },
            { it.optimizeLevelStyleCompaction(8 * 1024 * 1024L) },
            { it.optimizeUniversalStyleCompaction(8 * 1024 * 1024L) },
            { it.prepareForBulkLoad() },
        )
        presets.forEachIndexed { index, configure ->
            Options().setCreateIfMissing(true).use { options ->
                configure(options)
                openRocksDB(options, createTestDBFolder("ExpandedOptionsTest_preset_$index")).use { db ->
                    db.put(byteArrayOf(0, 1), byteArrayOf(0, 2))
                    FlushOptions().setWaitForFlush(true).use { db.flush(it) }
                    assertContentEquals(byteArrayOf(0, 2), db.get(byteArrayOf(0, 1)))
                }
            }
        }
        ColumnFamilyOptions().use { options ->
            options.optimizeForPointLookup(8)
            options.optimizeLevelStyleCompaction(8 * 1024 * 1024L)
            assertEquals(CompactionStyle.LEVEL, options.compactionStyle())
            options.optimizeUniversalStyleCompaction(8 * 1024 * 1024L)
            assertEquals(CompactionStyle.UNIVERSAL, options.compactionStyle())
        }
    }

    @Test
    fun startupTuningPersistsAndSurvivesReopen() {
        val path = createTestDBFolder("ExpandedOptionsTest_persisted")
        Options().setCreateIfMissing(true)
            .setMaxBackgroundJobs(2).setMaxSubcompactions(2)
            .setBytesPerSync(8192).setWalBytesPerSync(4096)
            .setMaxOpenFiles(64).setAtomicFlush(true)
            .setTtl(7200).setPeriodicCompactionSeconds(3600)
            .setOptimizeFiltersForHits(true)
            .setCompactionPriority(CompactionPriority.MinOverlappingRatio).use { options ->
                openRocksDB(options, path).use { db -> db.put(byteArrayOf(7), byteArrayOf(9)) }
                ConfigOptions().use { config ->
                    DBOptions().use { loaded ->
                        val descriptors = mutableListOf<ColumnFamilyDescriptor>()
                        try {
                            OptionsUtil.loadLatestOptions(config, path, loaded, descriptors)
                            assertEquals(2, loaded.maxBackgroundJobs())
                            assertEquals(8192L, loaded.bytesPerSync())
                            assertEquals(4096L, loaded.walBytesPerSync())
                            assertTrue(loaded.atomicFlush())
                            val family = descriptors.single().getOptions()
                            assertEquals(7200L, family.ttl())
                            assertEquals(3600L, family.periodicCompactionSeconds())
                            assertTrue(family.optimizeFiltersForHits())
                            assertEquals(CompactionPriority.MinOverlappingRatio, family.compactionPriority())
                        } finally {
                            descriptors.forEach { it.getOptions().close() }
                        }
                    }
                }
                openRocksDB(options, path).use { db ->
                    assertContentEquals(byteArrayOf(9), db.get(byteArrayOf(7)))
                }
            }
    }
